public class RepeatingDigit {
    public static void main(String[] args) {
        int n = 5;
        for (int i = 1; i <= n; i++) {
            System.out.println("11");
            System.out.println("22");
            System.out.println("33");
            System.out.println("44");
            System.out.println("55");
            break;
        }
    }
}
